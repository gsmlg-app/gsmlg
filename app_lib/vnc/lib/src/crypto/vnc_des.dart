  /// Reverses the bit order of an 8-bit byte as required by RFC 6143 VNC Auth.
  static int reverseBits(int byte) {
    var b = byte & 0xFF;
    var reversed = 0;
    for (var i = 0; i < 8; i++) {
      reversed = (reversed << 1) | (b & 1);
      b >>>= 1;
    }
    return reversed;
  }

  /// Encrypts a single 8-byte [block8] with an 8-byte [key8] using FIPS 46-3
  /// DES in ECB mode.
  static Uint8List encryptBlock(Uint8List block8, Uint8List key8) {
    if (block8.length != 8) {
      throw ArgumentError.value(block8.length, 'block8', 'Must be 8 bytes');
    }
    if (key8.length != 8) {
      throw ArgumentError.value(key8.length, 'key8', 'Must be 8 bytes');
    }

    final subkeys = _generateSubkeys(_bytesToUint64(key8));
    final block = _bytesToUint64(block8);
    final permuted = _permute(block, 64, _ip);

    var left = (permuted >>> 32) & 0xFFFFFFFF;
    var right = permuted & 0xFFFFFFFF;

    for (var round = 0; round < 16; round++) {
      final fOut = _feistel(right, subkeys[round]);
      final nextRight = (left ^ fOut) & 0xFFFFFFFF;
      left = right;
      right = nextRight;
    }

    final preOutput = ((right & 0xFFFFFFFF) << 32) | (left & 0xFFFFFFFF);
    final cipher = _permute(preOutput, 64, _fp);
    return _uint64ToBytes(cipher);
  }

  /// Encrypts a 16-byte RFC 6143 VNC Auth [challenge16] with [password].
  ///
  /// The password is truncated or zero-padded to 8 bytes, each byte has its
  /// bit order reversed per RFB VNC Auth, and the two 8-byte halves of
  /// [challenge16] are encrypted independently in DES-ECB mode.
  static Uint8List encryptChallenge(Uint8List challenge16, String password) {
    if (challenge16.length != 16) {
      throw ArgumentError.value(
        challenge16.length,
        'challenge16',
        'Must be 16 bytes',
      );
    }

    final pwBytes = utf8.encode(password);
    final key = Uint8List(8);
    final copyLen = pwBytes.length < 8 ? pwBytes.length : 8;
    for (var i = 0; i < copyLen; i++) {
      key[i] = reverseBits(pwBytes[i]);
    }

    final firstHalf = encryptBlock(challenge16.sublist(0, 8), key);
    final secondHalf = encryptBlock(challenge16.sublist(8, 16), key);

    final out = Uint8List(16);
    out.setRange(0, 8, firstHalf);
    out.setRange(8, 16, secondHalf);
    return out;
  }

  static List<int> _generateSubkeys(int key64) {
    final key56 = _permute(key64, 64, _pc1);
    var c = (key56 >>> 28) & 0x0FFFFFFF;
    var d = key56 & 0x0FFFFFFF;

    final subkeys = List<int>.filled(16, 0);
    for (var round = 0; round < 16; round++) {
      final shift = _shifts[round];
      c = _rotl28(c, shift);
      d = _rotl28(d, shift);
      final cd = (c << 28) | d;
      subkeys[round] = _permute(cd, 56, _pc2);
    }
    return subkeys;
  }

  static int _feistel(int halfBlock32, int subkey48) {
    final expanded = _permute(halfBlock32 & 0xFFFFFFFF, 32, _e);
    final xored = expanded ^ subkey48;

    var sOut = 0;
    for (var box = 0; box < 8; box++) {
      final chunk = (xored >>> (42 - box * 6)) & 0x3F;
      final row = ((chunk >>> 4) & 0x02) | (chunk & 0x01);
      final col = (chunk >>> 1) & 0x0F;
      final val = _sBoxes[box][(row << 4) | col];
      sOut = (sOut << 4) | val;
    }

    return _permute(sOut, 32, _p) & 0xFFFFFFFF;
  }

  static int _permute(int input, int inputWidth, List<int> table) {
    var output = 0;
    for (var i = 0; i < table.length; i++) {
      final bit = (input >>> (inputWidth - table[i])) & 1;
      output = (output << 1) | bit;
    }
    return output;
  }

  static int _rotl28(int value, int shift) =>
      ((value << shift) | (value >>> (28 - shift))) & 0x0FFFFFFF;

  static int _bytesToUint64(Uint8List bytes) {
    var value = 0;
    for (var i = 0; i < 8; i++) {
      value = (value << 8) | (bytes[i] & 0xFF);
    }
    return value;
  }

  static Uint8List _uint64ToBytes(int value) {
    final out = Uint8List(8);
    for (var i = 0; i < 8; i++) {
      out[i] = (value >>> (56 - i * 8)) & 0xFF;
    }
    return out;
  }
