List<String> starterPromptsForLanguage(String language) {
  final normalized = language.trim().toLowerCase().replaceAll('_', '-');
  if (normalized.startsWith('zh') ||
      normalized.contains('chinese') ||
      normalized.contains('mandarin') ||
      normalized.contains('中文') ||
      normalized.contains('普通话')) {
    return chineseStarterPrompts;
  }
  return englishStarterPrompts;
}
